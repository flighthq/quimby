  '# server writes nothing, ever). The distinction is already in the file — a real snapshot carries',
  "# an 'Updated:' line and the creation-time placeholder deliberately does not — but `cat` threw it",
  '# away, and three agents each invented a different explanation for the same never-populated',
  '# mirror ("builders wrote stale content", "distribution died Jul 31"). Never-reported and',
  '# reported-long-ago look identical if you only print the body.',
  'qa_mirror_age() {',
  '  updated=$(sed -n \'s/^Updated: *//p\' "$1" 2>/dev/null | head -n 1)',
  '  if [ -z "$updated" ]; then',
  "    echo 'never reported'",
  '    return 0',
  '  fi',
  '  # Age in whole days from the file itself, so this needs no date parsing beyond what sh has.',
  '  now=$(date +%s 2>/dev/null || echo 0)',
  '  then_=$(date -r "$1" +%s 2>/dev/null || echo 0)',
  '  if [ "$now" -gt 0 ] && [ "$then_" -gt 0 ]; then',
  '    days=$(( (now - then_) / 86400 ))',
  '    if [ "$days" -gt 0 ]; then',
  '      printf \'updated %sd ago\\n\' "$days"',
  '      return 0',
  '    fi',
  '  fi',
  "  echo 'updated recently'",
  '}',
  '',
  'cmd_peers() {',
  '  sdir="$ROOT/status"',
  '  if [ $# -gt 0 ]; then',
  '    f="$sdir/$1.md"',
  '    [ -f "$f" ] || qa_die "peers: no status mirror for \'$1\'"',
  '    printf \'── %s (%s) ──\\n\' "$1" "$(qa_mirror_age "$f")"',
  '    cat "$f"',
  '    return 0',
  '  fi',
  '  [ -d "$sdir" ] || { echo \'(no peers)\'; return 0; }',
  '  found=0',
  '  for f in "$sdir"/*.md; do',
  '    [ -f "$f" ] || continue',
  '    found=1',
