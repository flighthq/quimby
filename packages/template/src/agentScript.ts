  'cmd_handoff() {',
  '  mode=$1',
  '  shift',
  "  recipient=''",
  "  message=''",
  "  attach=''",
  "  replyto=''",
  '  publish=1',
  "  files=''",
  '  while [ $# -gt 0 ]; do',
  '    case $1 in',
  '      -m|--message) shift; [ $# -gt 0 ] || qa_die "handoff: -m needs a message"; message=$1 ;;',
  '      --attach) shift; [ $# -gt 0 ] || qa_die "handoff: --attach needs an agent"; attach=$1 ;;',
  '      --to) shift; [ $# -gt 0 ] || qa_die "reply: --to needs a parcel name"; replyto=$1 ;;',
