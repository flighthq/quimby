  '      # asymmetry with `status set --file` (where the file IS the content) sent real parcels out',
  '      # with empty notes, so the body has its own flag rather than an overloaded one.',
  '      --note-file)',
  '        shift',
  '        [ $# -gt 0 ] || qa_die "handoff: --note-file needs a path"',
  '        if [ "$1" = "-" ]; then',
  '          qa_nf=$(qa_read_stdin)',
  '          message=$(cat "$qa_nf")',
  '          rm -f "$qa_nf"',
  '        else',
  '          [ -f "$1" ] || qa_die "handoff: --note-file not found: $1"',
  '          message=$(cat "$1")',
  '        fi',
  '        ;;',
  '      --draft) publish=0 ;;',
  '      -*) qa_die "handoff: unknown option $1" ;;',
  '      *) if [ -z "$recipient" ]; then recipient=$1; else qa_die "handoff: unexpected arg $1"; fi ;;',
  '    esac',
  '    shift',
  '  done',
  '  [ -n "$recipient" ] || qa_die "handoff: recipient required (handoff <recipient> [-m msg] [--attach agent] [--file path])"',
  '  case $recipient in',
  '    */*|.|..) qa_die "handoff: invalid recipient \'$recipient\'" ;;',
  '  esac',
  '  # Refuse an address that cannot be delivered, rather than queueing a parcel that bounces where',
  '  # only the host sees it. Named the same way `reply --to` refuses an unknown parcel.',
  '  if [ -n "$QA_GRAPH" ] && ! qa_in_list "$recipient" "$QA_ROSTER"; then',
  '    printf \'agent.sh: %s: "%s" is not an agent.\\n\' "$mode" "$recipient" >&2',
  '    printf \'  roster: %s\\n\' "$QA_ROSTER" >&2',
  '    qa_die "$mode: address one of those (the roster refreshes on launch and on quimby sync)"',
  '  fi',
  '  # An --attach naming no agent fails host-side as a FAILED carry, which retries every cycle —',
  '  # so it warns forever rather than once. Cheaper to refuse here.',
  '  if [ -n "$QA_GRAPH" ] && [ -n "$attach" ] && ! qa_in_list "$attach" "$QA_ROSTER"; then',
  '    printf \'agent.sh: %s: --attach "%s" is not an agent.\\n\' "$mode" "$attach" >&2',
  '    printf \'  roster: %s\\n\' "$QA_ROSTER" >&2',
  '    qa_die "$mode: attach one of those, or drop --attach to send your own work"',
  '  fi',
  '  # An escalation aimed outside the permitted set is silently normalized to an ordinary advisory',
  '  # by the host — delivered, but waking nobody. That silence is the whole failure, so name it.',
  '  if [ -n "$QA_GRAPH" ] && [ "$mode" = escalate ]; then',
  '    if [ -z "$QA_ESCALATE" ]; then',
  "      printf 'agent.sh: escalate: you have no escalation target.\\n' >&2",
  '      qa_die "escalate: everything you send is advisory — use handoff, or record it with status"',
  '    fi',
  '    if ! qa_in_list "$recipient" "$QA_ESCALATE"; then',
  '      printf \'agent.sh: escalate: you may not escalate to "%s".\\n\' "$recipient" >&2',
  '      printf \'  permitted: %s\\n\' "$QA_ESCALATE" >&2',
  '      qa_die "escalate: name exactly one of those (an unpermitted escalation wakes nobody)"',
  '    fi',
  '  fi',
  '  [ "$mode" != delegate ] || [ -n "$message" ] || qa_die "delegate: message required"',
  '  # An escalation or a reply with no body is a wake carrying nothing — the recipient is',
  '  # interrupted and sent to read an empty note. Refuse rather than deliver that.',
  '  [ "$mode" != escalate ] || [ -n "$message" ] ||',
  '    qa_die "escalate: -m (or --note-file) required — summoning someone with no explanation wastes the interrupt"',
  '  [ "$mode" != reply ] || [ -n "$message" ] ||',
  '    qa_die "reply: -m (or --note-file) required — an answer needs a body"',
  '  # A note-less handoff is legitimate (a pure diff), but a note-less one carrying ATTACHED FILES',
  '  # is nearly always this mistake: --file attaches, it does not supply the body. Say so here,',
  '  # where it can still be fixed, rather than delivering an empty note to a peer.',
  '  if [ -z "$message" ] && [ -n "$files" ]; then',
  '    echo "agent.sh: WARNING publishing with an EMPTY note while attaching files." >&2',
  '    echo "          --file ATTACHES a file; it does not supply the note body (status --file does)." >&2',
  '    echo "          Use -m or --note-file <path> for the body." >&2',
  '  fi',
  '  [ "$mode" != reply ] || [ -n "$replyto" ] || qa_die "reply: --to <parcel> required (the question you are answering)"',
  '  # Fail here, not silently at the host: the reply-interrupt is honored only if the named parcel',
  '  # really reached this inbox, so a wrong name would publish fine and then wake nobody.',
  '  if [ "$mode" = reply ] && [ ! -d "$ROOT/handoff/in/received/$replyto" ] \\',
  '     && [ ! -d "$ROOT/handoff/in/processed/$replyto" ] \\',
  '     && ! grep -qxF "$replyto" "$ROOT/handoff/in/processed.ledger" 2>/dev/null; then',
  '    printf \'agent.sh: reply: "%s" is not a parcel you received.\\n\' "$replyto" >&2',
  "    printf 'Your inbox holds:\\n' >&2",
  '    ls -1 "$ROOT/handoff/in/received" 2>/dev/null | sed \'s/^/  /\' >&2 || true',
  '    qa_die "reply: use one of those names, or send an ordinary handoff instead"',
  '  fi',
  '  # The interrupt-intent tag by verb; the host validates it against the directs graph (§6).',
  "  fm=''",
  '  case $mode in',
  "    delegate) fm='delegated: true' ;;",
  "    escalate) fm='escalate: true' ;;",
  "    ask) fm='expects-reply: true' ;;",
  '    reply) fm="reply-to: $replyto" ;;',
  '  esac',
  '  draft="$ROOT/handoff/out/draft/$recipient"',
  '  rm -rf "$draft"',
  '  qa_mkdir "$draft"',
  // A leading '---' would be read as options by some printf implementations, so lead with %s.
  '  if [ -n "$fm" ] || [ -n "$attach" ]; then',
  "    printf '%s\\n' '---' > \"$draft/README.md\"",
  '    [ -z "$fm" ] || printf \'%s\\n\' "$fm" >> "$draft/README.md"',
  '    [ -z "$attach" ] || printf \'attach: %s\\n\' "$attach" >> "$draft/README.md"',
  "    printf '%s\\n' '---' >> \"$draft/README.md\"",
  '    printf \'%s\\n\' "$message" >> "$draft/README.md"',
  '  else',
  '    printf \'%s\\n\' "$message" > "$draft/README.md"',
  '  fi',
  '  for f in $files; do',
  '    [ -f "$f" ] || qa_die "handoff: --file not found: $f"',
  '    cp "$f" "$draft/"',
