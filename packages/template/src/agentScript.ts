  '        echo "          threads, next step); append within an arc, rewrite at the end of one." >&2',
  '      fi',
  '      ;;',
  '    *) qa_die "status: unknown subcommand \'$sub\' (show | set | append | done)" ;;',
  '  esac',
  '}',
