  '    *) qa_die "assignment: unknown subcommand \'$sub\' (show | set -m text | set --file path)" ;;',
  '  esac',
  '}',
  '',
  'cmd_status() {',
  '  if [ $# -gt 0 ]; then sub=$1; shift; else sub=show; fi',
  '  case $sub in',
  '    show)',
  '      cat "$ROOT/status.md"',
  '      ;;',
  '    set|append|done)',
  "      message=''",
  "      file=''",
  '      while [ $# -gt 0 ]; do',
  '        case $1 in',
  '          -m|--message) shift; [ $# -gt 0 ] || qa_die "status $sub: -m needs text"; message=$1 ;;',
  '          --file) shift; [ $# -gt 0 ] || qa_die "status $sub: --file needs a path"; file=$1 ;;',
  '          -*) qa_die "status $sub: unknown option $1" ;;',
  '          *) qa_die "status $sub: unexpected arg $1" ;;',
  '        esac',
  '        shift',
  '      done',
  '      if [ "$sub" = done ] && [ -z "$message" ] && [ -z "$file" ]; then message=done.; fi',
  '      if [ -n "$file" ]; then',
  '        [ "$file" = "-" ] || [ -f "$file" ] || qa_die "status $sub: --file not found: $file"',
  '        if [ "$file" = "-" ]; then src=$(qa_read_stdin); else src=$file; fi',
  '        if [ "$sub" = set ]; then cp "$src" "$ROOT/status.md"; else cat "$src" >> "$ROOT/status.md"; fi',
  '        [ "$file" = "-" ] && rm -f "$src"',
  '      else',
  '        [ -n "$message" ] || qa_die "status $sub: provide -m or --file"',
  '        if [ "$sub" = set ]; then printf \'%s\\n\' "$message" > "$ROOT/status.md"; else printf \'\\n%s\\n\' "$message" >> "$ROOT/status.md"; fi',
  '      fi',
  '      echo "agent.sh: status $sub"',
  '      # `append` is the easy path and `set` the effortful one, so a status journal only ever',
  '      # grows — and its whole job is to be the ONE thing a successor reads after a reset. Past a',
  '      # few thousand words that successor reads history to find the present, and superseded',
  '      # present-tense claims sit there looking current. A warning, never a refusal: what belongs',
  '      # in it is judgment, and this tool only does mechanics.',
  '      qa_bytes=$(wc -c < "$ROOT/status.md" 2>/dev/null || echo 0)',
  '      if [ "$qa_bytes" -gt 16000 ]; then',
  '        printf \'agent.sh: status.md is %s bytes — long enough that a successor reads history\\n\' "$qa_bytes" >&2',
