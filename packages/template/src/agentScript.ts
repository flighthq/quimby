  '  recipient=$1',
  '  draft="$ROOT/handoff/out/draft/$recipient"',
  '  [ -d "$draft" ] || qa_die "publish: no draft for \'$recipient\'"',
  '  qa_mkdir "$ROOT/handoff/out/queued"',
  '  queued="$ROOT/handoff/out/queued/$recipient"',
  '  rm -rf "$queued"',
  '  mv "$draft" "$queued"',
  '  # Name what the parcel CONTAINS, not just that it was queued. Agents were sending a note and',
  '  # then reaching for a second step to send their commits — because nothing here said the note',
  '  # and the work travel together. One parcel, one move; there is no separate verb for the code.',
  '  echo "agent.sh: queued parcel for \'$recipient\' — carries your note AND your work (everything in"',
  '  echo "          repo/ since quimby/seed: commits + uncommitted). One parcel; nothing else to send."',
  '  qa_carry_summary',
  '  echo "          quimby dispatch carries it (the server also auto-dispatches)."',
  '}',
  '',
  'qa_read_stdin() {',
  '  tmp=$(mktemp)',
  '  cat > "$tmp"',
  '  printf \'%s\\n\' "$tmp"',
  '}',
  '',
  'cmd_assignment() {',
  '  if [ $# -gt 0 ]; then sub=$1; shift; else sub=show; fi',
  '  case $sub in',
  '    show)',
  '      cat "$ROOT/assignment.md"',
  '      ;;',
  '    set)',
  "      message=''",
  "      file=''",
  '      while [ $# -gt 0 ]; do',
  '        case $1 in',
  '          -m|--message) shift; [ $# -gt 0 ] || qa_die "assignment set: -m needs text"; message=$1 ;;',
  '          --file) shift; [ $# -gt 0 ] || qa_die "assignment set: --file needs a path"; file=$1 ;;',
